# Ingestion degrades per document instead of failing a batch, hence the broad excepts.
"""
Non-daemonic subprocess helper for parallel PyMuPDF4LLM extraction.

task-queue's default prefork pool runs each task in a daemonic child process, and
Python forbids daemonic processes from spawning `ProcessPoolExecutor` children.
That is why `pymupdf4llm_ingestor._extract_parallel` is gated off whenever
`multiprocessing.current_process().daemon` is True (see the `is_daemonic`
check in the ingestor) and we fall back to a single-threaded extraction -
which takes 10-30 minutes for a 1000+ page PDF.

This module is invoked by the ingestor via `subprocess.run`. Because
`subprocess.Popen` creates a *non-daemonic* OS child, this process CAN in
turn spawn a `ProcessPoolExecutor`, so we get true N-core parallelism for
the CPU-bound pymupdf4llm extraction.

WARNING (security): This is an INTERNAL helper. Do not invoke it with paths
from untrusted sources. Paths MUST be generated by the calling process. The
input/output files use JSON (not pickle) so deserialization cannot execute
arbitrary code; however an attacker with filesystem write access could still
cause misparsing or schema drift if they replaced the output file between
our `subprocess.run` return and our `json.load`.

Invocation (internal use only)::

    python -m legal_rag.ingestion.pymupdf_extract_subprocess \\
        --config <path-to-input-json> \\
        --out    <path-to-output-json>

Input::

    The PyMuPDF Pro licence key, if any, is read from standard input.

"""

from __future__ import annotations

import argparse
import json
import logging
import os
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed

__all__ = ["extract_pdf_parallel", "main", "plan_page_ranges"]

logging.basicConfig(
    level="INFO",
    format="[pymupdf-subprocess] %(asctime)s %(levelname)s %(message)s",
    stream=sys.stderr,
)
log = logging.getLogger(__name__)


# =========================================================================
# CPU detection
# =========================================================================


def _available_cpus() -> int:
    """Return the number of CPUs actually usable by this process.

    Prefers `os.sched_getaffinity(0)` on Linux because it respects cgroup
    CPU quotas - important in container orchestration where `os.cpu_count()`
    reports the host's cores, not the cgroup's effective share.
    """
    try:
        return len(os.sched_getaffinity(0))  # type: ignore[attr-defined]
    except AttributeError:
        # macOS / Windows: no sched_getaffinity. Fall back to cpu_count.
        return os.cpu_count() or 4


# =========================================================================
# PyMuPDF activation (parent process). Child processes re-activate inside
# `_parse_page_range` so fork-vs-spawn differences don't leak.
# =========================================================================


def _activate_pymupdf_pro(pro_api_key: str) -> bool:
    """Unlock PyMuPDF Pro for this process. Returns True if unlocked."""
    if not pro_api_key:
        return False
    try:
        import pymupdf.pro

        pymupdf.pro.unlock(pro_api_key)
        log.info("pymupdf_pro_unlocked")
        return True
    except ImportError:
        log.warning("pymupdf_pro_module_missing")
    except Exception as e:
        log.warning("pymupdf_pro_unlock_failed error=%s", e)
    return False


def _activate_pymupdf_layout() -> bool:
    """Activate the GNN layout engine. Must run BEFORE importing pymupdf4llm
    so `to_markdown` picks up the layout hooks."""
    try:
        import pymupdf.layout  # noqa: F401

        log.info("pymupdf_layout_activated")
        return True
    except ImportError:
        log.warning("pymupdf_layout_module_missing")
        return False


# =========================================================================
# Page-range planner (shared with the in-process _extract_parallel path).
# =========================================================================


def plan_page_ranges(
    total_pages: int,
    num_workers_cap: int,
    min_pages_per_worker: int,
) -> list[list[int]]:
    """Split pages into contiguous ranges, one per worker.

    Produces identical output to ``_extract_parallel``'s inline planner so
    callers can rely on byte-for-byte consistent page_chunks regardless of
    which extraction path ran.

    Returns an empty list if ``total_pages`` is 0 (no work).
    """
    if total_pages <= 0:
        return []

    cpu = _available_cpus()
    # At least one worker, cap at the parameter, and don't exceed either the
    # per-worker minimum page budget or the available CPUs.
    num_workers = min(
        max(1, num_workers_cap),
        max(1, total_pages // max(1, min_pages_per_worker)),
        cpu,
    )
    num_workers = max(1, num_workers)

    pages_per_worker = total_pages // num_workers
    remainder = total_pages % num_workers
    ranges: list[list[int]] = []
    start = 0
    for i in range(num_workers):
        end = start + pages_per_worker + (1 if i < remainder else 0)
        ranges.append(list(range(start, end)))
        start = end
    return ranges


# =========================================================================
# Public API
# =========================================================================


def extract_pdf_parallel(
    pdf_path: str,
    total_pages: int,
    *,
    common_kwargs: dict | None = None,
    pro_api_key: str = "",
    num_workers_cap: int = 14,
    min_pages_per_worker: int = 32,
) -> list[dict]:
    """Parallel PyMuPDF4LLM extraction from a non-daemonic caller.

    This is the single entrypoint for both the CLI (``python -m ...``) and
    for tests / ad-hoc scripts that already run in a non-daemonic process.
    Returns a list of page chunk dicts in ascending page order. Shape matches
    ``_parse_page_range`` in the sibling ingestor module.

    Raises:
        RuntimeError: if any worker process fails. The exception message
            includes the page range that blew up so prod logs point at the
            culprit immediately.
    """
    _activate_pymupdf_pro(pro_api_key)
    _activate_pymupdf_layout()

    # Deferred import - must happen after layout activation. We reuse
    # `_parse_page_range` so output matches the in-process parallel path.
    from legal_rag.ingestion.pymupdf4llm_ingestor import _parse_page_range

    # If the parent passed total_pages=0 it means the parent could not
    # safely call pymupdf.open() in its own process (office files in a
    # daemonic task-queue worker - pymupdf.open on .xlsx/.docx triggers the
    # PyMuPDF Pro Excel→PDF conversion path that fork-deadlocks). We are
    # in a fresh non-daemonic subprocess here, so opening is safe; do it
    # ourselves to discover the real page count.
    if total_pages <= 0:
        try:
            import pymupdf

            doc = pymupdf.open(pdf_path)
            total_pages = len(doc)
            doc.close()
            log.info("subprocess_resolved_page_count total_pages=%d", total_pages)
        except Exception as e:
            log.warning("subprocess_page_count_failed error=%s", e)
            return []

    page_ranges = plan_page_ranges(total_pages, num_workers_cap, min_pages_per_worker)
    if not page_ranges:
        return []

    config_dict = {"pro_api_key": pro_api_key, **(common_kwargs or {})}

    log.info(
        "extract_parallel_start total_pages=%d num_workers=%d pages_per_worker=%s",
        total_pages,
        len(page_ranges),
        [len(r) for r in page_ranges],
    )

    t0 = time.monotonic()

    # submit + as_completed (instead of pool.map) so we can report which
    # page range triggered a BrokenProcessPool / OOM / pymupdf crash.
    results_by_first_page: dict[int, list[dict]] = {}
    worker_args = [(pdf_path, pr, config_dict) for pr in page_ranges]

    with ProcessPoolExecutor(max_workers=len(page_ranges)) as pool:
        future_to_range = {pool.submit(_parse_page_range, wa): wa[1] for wa in worker_args}
        for fut in as_completed(future_to_range):
            pages = future_to_range[fut]
            first, last = pages[0], pages[-1]
            try:
                results_by_first_page[first] = fut.result()
            except Exception as e:
                # Surface which range failed - critical for debugging
                # 5000-page PDFs in prod.
                raise RuntimeError(
                    f"pymupdf worker failed on pages {first}..{last}: {type(e).__name__}: {e}"
                ) from e

    # Reassemble in ascending page order. Dict ordering since 3.7 is
    # insertion order, but as_completed yields in completion order - sort
    # to enforce the contract.
    merged: list[dict] = []
    for first in sorted(results_by_first_page):
        merged.extend(results_by_first_page[first])

    elapsed = time.monotonic() - t0
    log.info(
        "extract_parallel_complete total_pages=%d merged_chunks=%d elapsed_s=%.2f",
        total_pages,
        len(merged),
        elapsed,
    )
    return merged


# =========================================================================
# CLI adapter
# =========================================================================


def _write_error(out_path: str, error: Exception, page_range: list[int] | None) -> None:
    """Write a machine-readable error sentinel so the parent can tell a
    crash apart from a successful empty-result extraction."""
    payload = {
        "__error__": str(error),
        "__error_type__": type(error).__name__,
        "__page_range__": page_range,
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(payload, f)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Non-daemonic PyMuPDF4LLM extraction worker (internal)",
    )
    parser.add_argument("--config", required=True, help="Path to input JSON")
    parser.add_argument("--out", required=True, help="Path to write output JSON")
    args = parser.parse_args()

    try:
        with open(args.config, encoding="utf-8") as f:
            cfg = json.load(f)
    except Exception as e:
        log.exception("config_load_failed")
        _write_error(args.out, e, None)
        return 1

    # The licence key arrives on stdin for secret hygiene. The config JSON never
    # touches disk with the key.
    pro_api_key = sys.stdin.read().strip()

    try:
        page_chunks = extract_pdf_parallel(
            pdf_path=cfg["pdf_path"],
            total_pages=int(cfg["total_pages"]),
            common_kwargs=cfg.get("common_kwargs") or {},
            pro_api_key=pro_api_key,
            num_workers_cap=int(cfg.get("num_workers") or 8) or 8,
            min_pages_per_worker=int(cfg.get("min_pages_per_worker") or 32) or 32,
        )
    except Exception as e:
        log.exception("extraction_failed")
        # Try to pluck the page range out of the error message if we raised it.
        page_range: list[int] | None = None
        _write_error(args.out, e, page_range)
        return 1

    with open(args.out, "w", encoding="utf-8") as f:
        # Ensure non-ASCII page text round-trips safely.
        json.dump(page_chunks, f, ensure_ascii=False)

    return 0


if __name__ == "__main__":
    sys.exit(main())
