"""Query and ingest pipelines built from small stages, plus the types and tier data they share.

Query side: ``QueryPipeline`` resolves a tier, checks a semantic cache and an exact cache, then runs
the ``analyze``, ``retrieve``, ``rerank`` and ``context`` stages and returns a ``QueryResult``.
Ingest side: ``IngestPipeline`` turns a document into embedded, written chunks.
Each stage is also importable on its own, as ``async def stage(ctx, **collaborators) -> ctx``.

Opt-in jurisdiction behavior lives in the ``jurisdictions`` registry (``pipeline.jurisdictions``),
for example ``jurisdictions.get("us", case_retriever=..., statute_retriever=...)``.
Nothing here knows a tenant, user or billing key: pass an opaque ``filters`` mapping on the request
and apply it in your retriever and chunk fetcher.
"""

